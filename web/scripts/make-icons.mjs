// Builds components/icons/generated.tsx from icon-kit's offline Iconify data (set ICON_KIT_DIR). Add an icon: one line in icons.config.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const KITS = process.env.ICON_KIT_DIR
if (!KITS) throw new Error('Set ICON_KIT_DIR to the folder of Iconify kit JSON files (icon-kit: packages/core/kits).')
const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const cfg = JSON.parse(readFileSync(here('./icons.config.json'), 'utf8'))
const kit = JSON.parse(readFileSync(`${KITS}/${cfg.kit}.json`, 'utf8'))
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const jsx = (svg) => svg.replace(/([a-z-]+)=("[^"]*")/g, (_, k, v) => `${k.includes('-') ? camel(k) : k}=${v}`)

const out = [
  "// Generated by scripts/make-icons.mjs from icon-kit (lucide, ISC). Do not edit by hand.",
  "import type { SVGProps } from 'react'",
  '',
  "type P = SVGProps<SVGSVGElement> & { size?: number }",
  "const base = ({ size = 16, ...p }: P) => ({ width: size, height: size, viewBox: '0 0 24 24', 'aria-hidden': true as const, focusable: false as const, strokeLinecap: 'square' as const, strokeLinejoin: 'miter' as const, ...p })",
  '',
]
for (const [name, id] of Object.entries(cfg.icons)) {
  const icon = kit.icons[id] ?? kit.icons[kit.aliases?.[id]?.parent]
  if (!icon) throw new Error(`icon not in kit: ${id}`)
  // square caps and mitred joins give the line icons a blocky, technical feel
  const body = jsx(icon.body).replace(/strokeLinecap="round"/g, '').replace(/strokeLinejoin="round"/g, '')
  out.push(`export const ${name} = (p: P) => (\n  <svg {...base(p)}>${body}</svg>\n)`, '')
}
mkdirSync(here('../components/icons'), { recursive: true })
writeFileSync(here('../components/icons/generated.tsx'), out.join('\n'))
console.log(`${Object.keys(cfg.icons).length} icons written`)
